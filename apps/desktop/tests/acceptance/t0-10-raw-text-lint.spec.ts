/**
 * Acceptance tests for T-0.10: "a lint rule against raw strings in
 * templates" (AGENTS.md: "No hard-coded UI strings. All user-facing text
 * goes through `vue-i18n`").
 *
 * The tests lint components given as text, under the names of files in the
 * app, through ESLint's Node.js API with the project's own configuration,
 * which `pnpm lint` and the lefthook `desktop-eslint` job use too. Files on
 * disk are not read or changed. Which rule or plugin reports raw text is the
 * developer's choice, so the tests compare two versions of a component: one
 * whose text goes through vue-i18n (`t(...)`), which lints clean, and the
 * same component with one piece of raw text, which must get an error on the
 * line of that text.
 *
 * Contract (the rest is the developer's choice):
 *
 * 1. In the app's Vue components, raw text in a template is a lint error
 *    (severity "error", not a warning): text in an element, also next to
 *    an interpolation, a string literal shown with `{{ }}`, and a static
 *    value of the attributes that people read or hear: `aria-label`,
 *    `title`, `placeholder` and `alt`. This holds for every .vue file under
 *    src/ except the two exempt folders below; for example src/App.vue,
 *    src/pages/ and domain components in src/components/.
 * 2. Not reported: text that goes through vue-i18n (also in bound
 *    attributes), interpolated values, markup without text, attributes
 *    nobody reads (`class`, `id`, `type`, `role`, `data-*`, `aria-hidden`,
 *    ...), and text made only of whitespace and punctuation used as
 *    separators: `:` `/` `·` `•` `-` `–` `—` `|` `(` `)` and `&nbsp;`.
 * 3. Exempt from the rule (any other rule still applies there):
 *    - src/dev/**: the dev-only component gallery (T-0.8), which is not
 *      user-facing and is left out of production builds;
 *    - src/components/ui/**: components generated by the shadcn-vue CLI,
 *      kept as the CLI writes them (CONTRIBUTING.md).
 *
 * Not covered: a string literal bound to an attribute, such as
 * `:title="'Stop'"`, which the usual rules (eslint-plugin-vue's
 * `no-bare-strings-in-template`, @intlify/eslint-plugin-vue-i18n's
 * `no-raw-text`) do not report.
 *
 * Tests and the rules they cover:
 *
 * - "reports <raw text> as an error": rule 1.
 * - "reports raw text in <file>": rule 1, the files it applies to.
 * - "accepts <content>": rule 2.
 * - "does not apply the rule to <file>": rule 3.
 *
 * @vitest-environment node
 */

import { ESLint, type Linter } from "eslint";
import { describe, expect, it } from "vitest";

const linter = new ESLint();

/** Where raw text is reported (rule 1). */
const CHECKED_FILE = "src/pages/TimerPage.vue";

/**
 * A component whose script provides `t` (vue-i18n) and a number, and whose
 * template shows `body` on its own line. The last line uses both, so that
 * no `body` leaves them unused.
 */
function component(body: string): { code: string; bodyLine: number } {
  const before = [
    '<script setup lang="ts">',
    'import { useI18n } from "vue-i18n";',
    "",
    "const { t } = useI18n();",
    "const count = 3;",
    "</script>",
    "",
    "<template>",
    "  <main>",
  ];
  const after = [
    '    <p>{{ t("app.name") }} {{ count }}</p>',
    "  </main>",
    "</template>",
    "",
  ];
  return {
    code: [...before, `    ${body}`, ...after].join("\n"),
    bodyLine: before.length + 1,
  };
}

async function lintAs(
  filePath: string,
  code: string,
): Promise<Linter.LintMessage[]> {
  const results = await linter.lintText(code, { filePath, warnIgnored: true });
  return results.flatMap((result) => result.messages);
}

function describeMessages(messages: Linter.LintMessage[]): string[] {
  return messages.map(
    (message) =>
      `${message.line}:${message.column} ${message.ruleId ?? "(parse)"} ` +
      `severity ${message.severity}: ${message.message}`,
  );
}

/** Content that must lint clean (rule 2). */
const ACCEPTED: [string, string][] = [
  ["text through vue-i18n", '<p>{{ t("app.name") }}</p>'],
  [
    "translated attributes",
    `<button type="button" :aria-label="t('app.name')" :title="t('app.name')"></button>`,
  ],
  ["a translated placeholder", `<input :placeholder="t('app.name')" />`],
  ["a translated alt text", `<img :alt="t('app.name')" src="/icon.png" />`],
  ["interpolated values", "<span>{{ count }}</span>"],
  [
    "attributes nobody reads",
    '<div id="row" class="flex gap-2" data-test="row" role="status" aria-hidden="true"></div>',
  ],
  [
    "form attributes nobody reads",
    '<input id="minutes" type="number" name="minutes" autocomplete="off" />',
  ],
  ["a colon between values", "<span>{{ count }}:{{ count }}</span>"],
  [
    "separators",
    "<span>:</span><span> / </span><span>·</span><span>•</span><span>-</span><span>–</span><span>—</span><span>|</span><span>(</span><span>)</span>",
  ],
  ["a non-breaking space", "<span>&nbsp;</span>"],
  ["whitespace", "<span>   </span>"],
];

/** Raw text that must be an error (rule 1). */
const RAW: [string, string][] = [
  ["text in an element", "<p>Start focus</p>"],
  ["Spanish text in an element", "<p>Iniciar sesión</p>"],
  ["text next to an interpolation", "<p>{{ count }} sessions</p>"],
  ["a string literal in an interpolation", '<p>{{ "Start focus" }}</p>'],
  ["an aria-label", '<button type="button" aria-label="Stop"></button>'],
  ["a title", '<span title="Locked"></span>'],
  ["a placeholder", '<input placeholder="Website" />'],
  ["an alt text", '<img alt="Lock icon" src="/icon.png" />'],
];

describe("raw text in templates (T-0.10)", () => {
  it.each(ACCEPTED)("accepts %s", async (_name, body) => {
    const { code } = component(body);

    const messages = await lintAs(CHECKED_FILE, code);

    expect(describeMessages(messages)).toEqual([]);
  });

  it.each(RAW)("reports %s as an error", async (_name, body) => {
    const { code, bodyLine } = component(body);

    const messages = await lintAs(CHECKED_FILE, code);

    const errorsOnLine = messages.filter(
      (message) => message.line === bodyLine && message.severity === 2,
    );
    expect(
      errorsOnLine.length,
      `an error on line ${bodyLine}; got:\n${describeMessages(messages).join("\n")}`,
    ).toBeGreaterThan(0);
  });

  it.each([
    "src/App.vue",
    "src/pages/BlocklistsPage.vue",
    "src/components/TimerRing.vue",
    "src/components/blocklists/TargetRow.vue",
  ])("reports raw text in %s", async (filePath) => {
    const clean = component('<p>{{ t("app.name") }}</p>');
    const raw = component("<p>Start focus</p>");

    expect(describeMessages(await lintAs(filePath, clean.code))).toEqual([]);
    const messages = await lintAs(filePath, raw.code);
    expect(
      messages.filter(
        (message) => message.line === raw.bodyLine && message.severity === 2,
      ).length,
      describeMessages(messages).join("\n"),
    ).toBeGreaterThan(0);
  });

  it.each([
    "src/dev/ComponentGallery.vue",
    "src/dev/DevPreview.vue",
    "src/components/ui/button/Button.vue",
    "src/components/ui/sidebar/Sidebar.vue",
  ])("does not apply the rule to %s", async (filePath) => {
    const clean = component('<p>{{ t("app.name") }}</p>');
    const baseline = describeMessages(await lintAs(filePath, clean.code));

    for (const [name, body] of RAW) {
      const raw = component(body);
      const messages = describeMessages(await lintAs(filePath, raw.code));
      expect(messages, `${name} in ${filePath}`).toEqual(baseline);
    }
  });
});
