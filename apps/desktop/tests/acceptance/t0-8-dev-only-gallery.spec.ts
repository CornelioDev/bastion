/**
 * Acceptance tests for T-0.8: the component gallery is "dev-only", and the
 * app's stylesheet is built with Tailwind CSS v4 with a class-based dark
 * theme. The gallery itself is covered by t0-8-component-gallery.spec.ts,
 * whose top comment states the contract (src/dev/ComponentGallery.vue,
 * `data-gallery-component` and `data-gallery-theme-toggle` markers).
 *
 * The tests run a production build of the frontend, the `vite build` step
 * of `pnpm build`, with the project's own Vite config, into a temporary
 * directory (dist/ is not touched), and read what it wrote. The build runs
 * in a separate Node.js process with Vitest's variables removed from the
 * environment (NODE_ENV=test, VITEST, ...), so that it builds exactly what
 * `pnpm build` and `pnpm tauri build` ship.
 *
 * Criteria covered:
 *
 * - "dev-only": the gallery is not shipped in production builds, neither
 *   inlined in the app's code nor as a separate chunk or page that could be
 *   loaded later:
 *   "leaves the component gallery out of the production build".
 * - "Add Tailwind CSS v4": the production stylesheet is generated by
 *   Tailwind CSS v4, which leaves its `theme` and `utilities` layers and
 *   `--tw-` variables in the built CSS:
 *   "builds the app's stylesheet with Tailwind CSS v4".
 * - "in light and dark themes": the shipped stylesheet has styles for the
 *   dark theme selected by the `dark` class, the class that the gallery's
 *   theme toggle switches (no colors are checked; tokens are T-0.9):
 *   "ships styles for the dark theme selected by the dark class".
 *
 * The build is checked for the markers of the gallery's contract and for its
 * file name, in file names and in file contents. Production code has no
 * reason to use the `data-gallery-` attributes, which belong to the gallery.
 *
 * @vitest-environment node
 */

import { spawnSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

const appRoot = fileURLToPath(new URL("../..", import.meta.url));

/** Markers that only the gallery may contain. */
const GALLERY_MARKERS = [
  "data-gallery-component",
  "data-gallery-theme-toggle",
  "ComponentGallery",
];

interface BuiltFile {
  /** Path relative to the build's output directory, with forward slashes. */
  path: string;
  contents: string;
}

let outDir: string;
let files: BuiltFile[];

function listFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name));
}

function productionEnv(): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (key === "NODE_ENV" || key.startsWith("VITEST") || key === "TEST") {
      continue;
    }
    env[key] = value;
  }
  return env;
}

function cssFiles(): BuiltFile[] {
  return files.filter((file) => file.path.endsWith(".css"));
}

beforeAll(() => {
  outDir = mkdtempSync(join(tmpdir(), "bastion-t0-8-build-"));
  const vite = join(appRoot, "node_modules", "vite", "bin", "vite.js");
  const result = spawnSync(
    process.execPath,
    [vite, "build", "--outDir", outDir, "--emptyOutDir", "--logLevel", "warn"],
    { cwd: appRoot, env: productionEnv(), encoding: "utf8" },
  );
  expect(
    result.status,
    `vite build should succeed:\n${result.stdout}\n${result.stderr}`,
  ).toBe(0);

  files = listFiles(outDir).map((file) => ({
    path: relative(outDir, file).split(sep).join("/"),
    // Binary assets (fonts, images) read as text are harmless for a search.
    contents: readFileSync(file, "latin1"),
  }));
}, 180_000);

afterAll(() => {
  if (outDir !== undefined) {
    rmSync(outDir, { recursive: true, force: true });
  }
});

describe("production build (T-0.8)", () => {
  it("leaves the component gallery out of the production build", () => {
    // Guard against a vacuous pass: the build must contain the app.
    expect(files.map((file) => file.path)).toContain("index.html");
    expect(files.some((file) => file.path.endsWith(".js"))).toBe(true);

    const leaks = files.flatMap((file) =>
      GALLERY_MARKERS.filter(
        (marker) =>
          file.path.includes(marker) || file.contents.includes(marker),
      ).map((marker) => `${file.path}: ${marker}`),
    );

    expect(leaks, "no built file should contain the gallery").toEqual([]);
  });

  it("builds the app's stylesheet with Tailwind CSS v4", () => {
    const css = cssFiles();
    expect(css.length, "the build should contain a stylesheet").toBeGreaterThan(
      0,
    );

    // The minified build drops Tailwind's license banner, so the test looks
    // for what Tailwind CSS v4 generates: its `theme` and `utilities`
    // cascade layers (v3 had no `theme` layer) and its `--tw-` variables.
    const isTailwind4 = (contents: string): boolean =>
      /@layer theme\s*\{/.test(contents) &&
      /@layer utilities\s*\{/.test(contents) &&
      contents.includes("--tw-");
    expect(
      css.some((file) => isTailwind4(file.contents)),
      "a stylesheet should be generated by Tailwind CSS v4",
    ).toBe(true);
  });

  it("ships styles for the dark theme selected by the dark class", () => {
    expect(
      cssFiles().some((file) => /\.dark(?![\w-])/.test(file.contents)),
      "a stylesheet should have rules for the .dark class",
    ).toBe(true);
  });
});
